import { LoggerService } from '@nestjs/common';
import * as winston from 'winston';

/**
 * Implements Winston with JSON formatting, timestamps, log levels and APM-ready metadata
 */
export class WinstonAppLogger implements LoggerService {
  private logger: winston.Logger;

  constructor() {
    this.logger = winston.createLogger({
      level: process.env.LOG_LEVEL || 'info',
      format: winston.format.combine(
        winston.format.timestamp({ format: 'YYYY-MM-DD HH:mm:ss' }),
        winston.format.errors({ stack: true }),
        winston.format.json()
      ),
      defaultMeta: { service: 'campus-arena-api', environment: process.env.NODE_ENV || 'development' },
      transports: [
        new winston.transports.Console({
          format: winston.format.combine(
            winston.format.colorize(),
            winston.format.printf(({ timestamp, level, message, context, ...meta }) => {
              return `[${timestamp}] [${level}] [${context || 'Application'}]: ${message} ${
                Object.keys(meta).length > 1 ? JSON.stringify(meta) : ''
              }`;
            })
          ),
        }),
      ],
    });
  }

  log(message: any, context?: string) {
    this.logger.info(message, { context });
  }

  error(message: any, trace?: string, context?: string) {
    this.logger.error(message, { trace, context });
  }

  warn(message: any, context?: string) {
    this.logger.warn(message, { context });
  }

  debug?(message: any, context?: string) {
    this.logger.debug(message, { context });
  }
}
